package org.apache.dolphinscheduler.api.filter;

import java.io.IOException;

import javax.servlet.FilterChain;
import javax.servlet.ServletException;
import javax.servlet.http.HttpServletRequest;
import javax.servlet.http.HttpServletResponse;

import org.springframework.core.Ordered;
import org.springframework.core.annotation.Order;
import org.springframework.stereotype.Component;
import org.springframework.web.filter.OncePerRequestFilter;

@Component
@Order(Ordered.HIGHEST_PRECEDENCE)
public class DoSuffixForwardFilter extends OncePerRequestFilter {

    private static final String DO_SUFFIX = ".do";

    @Override
    protected void doFilterInternal(HttpServletRequest request,
                                    HttpServletResponse response,
                                    FilterChain filterChain) throws ServletException, IOException {
        String requestUri = request.getRequestURI();
        String contextPath = request.getContextPath();
        String requestPath = requestUri.substring(contextPath.length());

        if (requestPath.endsWith(DO_SUFFIX)) {
            String forwardPath = requestPath.substring(0, requestPath.length() - DO_SUFFIX.length());
            request.getRequestDispatcher(forwardPath).forward(request, response);
            return;
        }

        filterChain.doFilter(request, response);
    }
}
